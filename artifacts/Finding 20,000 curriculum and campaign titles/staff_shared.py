GAP_METHOD = [
 ["Name the outcome","Not the activity. 'Twelve trained group leaders by June' rather than 'improve group ministry.'"],
 ["Score where you are","One to five, honestly, on the competency map for your level. Guessing high wastes the quarter."],
 ["Find the largest gap","The biggest distance between current and required, not the one that is most comfortable to work on."],
 ["Name one action","One. Quarterly plans with six priorities have none."],
 ["Name the evidence","What will exist at the end of the quarter that does not exist now, that another person could look at."],
 ["Book the review","A date on a calendar with a named person. A gap analysis nobody reviews is a diary entry."],
]

